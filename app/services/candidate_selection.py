"""Evidence-based recommendations, never permission to release a repair.

Only freshly evaluated candidates with measurable audit improvements compete.
A unique non-dominated result is recommended. Where independent trials prove
*identical output bytes and audit findings*, a strictly simpler plan can win.
Real ties and trade-offs require a human choice. Audit evidence cannot prove
cell-level or business correctness.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Literal

from app.core.candidates import CandidateBatch
from app.core.policy import DatasetPolicy
from app.services.candidate_evaluation import CandidateEvaluation, evaluate_candidate_batch
from app.tools.audit import AuditReport

SEVERITY = {"INFO": 1, "WARNING": 2, "CRITICAL": 3}


@dataclass(frozen=True, slots=True)
class CandidateComparisonRow:
    """Explain whether a candidate participates in the comparison."""

    candidate_id: str
    evaluation_status: str
    disposition: Literal["EXCLUDED", "NO_MEASURED_IMPROVEMENT", "IMPROVING"]
    reason: str


@dataclass(frozen=True, slots=True)
class CandidateRecommendation:
    """Advisory result only: no output path, execution token, or release grant."""

    source_fingerprint_sha256: str
    status: Literal["RECOMMENDED", "HUMAN_CHOICE_REQUIRED", "NO_IMPROVING_CANDIDATE"]
    recommended_candidate_id: str | None
    shortlisted_candidate_ids: tuple[str, ...]
    rows: tuple[CandidateComparisonRow, ...]
    evaluations: tuple[CandidateEvaluation, ...]
    message: str


def _profile(report: AuditReport) -> dict[tuple[str, str | None], tuple[int, int]]:
    """Group findings by code and column, retaining severity and total count."""
    grouped: dict[tuple[str, str | None], tuple[int, int]] = {}
    for issue in report.issues:
        key = (issue.code, issue.column)
        severity, count = grouped.get(key, (0, 0))
        grouped[key] = (max(severity, SEVERITY[issue.severity]), count + issue.count)
    return grouped


def _improves(left: AuditReport, right: AuditReport) -> bool:
    """Left must reduce an observed finding/duplicate, without worsening another.

    Quality score alone is not evidence of improvement. Counts and severity
    are separate dimensions, so a reduction in one cannot hide growth in another.
    Row loss by itself is never rewarded. Regression checks handle row budgets.
    """
    left_profile, right_profile = _profile(left), _profile(right)
    pairs = [(left.duplicate_row_count, right.duplicate_row_count)]

    for key in left_profile.keys() | right_profile.keys():
        pairs.extend(zip(
            left_profile.get(key, (0, 0)),
            right_profile.get(key, (0, 0)),
            strict=True,
        ))

    return all(a <= b for a, b in pairs) and any(a < b for a, b in pairs)


def _dominates(left: AuditReport, right: AuditReport) -> bool:
    """No hidden weights: no worse on audit metrics, strictly better on evidence."""
    return (
        left.quality_score >= right.quality_score
        and not (right.status == "READY" and left.status != "READY")
        and _improves(left, right)
    )


def recommend_candidate_batch(
    source_file: str | Path,
    batch: CandidateBatch,
    *,
    dataset_policy: DatasetPolicy | None = None,
) -> CandidateRecommendation:
    """Run fresh trials and compare their results, without selecting for release.

    Source-integrity failures propagate. The input batch cannot provide scores,
    a winner, or permissions. Evidence is generated by the existing evaluator.
    """
    checked = CandidateBatch.model_validate(batch.model_dump(mode="python"))
    policy = (
        DatasetPolicy() if dataset_policy is None
        else DatasetPolicy.model_validate(dataset_policy.model_dump(mode="python"))
    )
    evaluations = evaluate_candidate_batch(source_file, checked, dataset_policy=policy)
    rows: list[CandidateComparisonRow] = []
    improving: dict[str, AuditReport] = {}

    for result in evaluations:
        trial = result.trial
        identifier = trial.assessment.candidate.candidate_id
        after = trial.audit_after

        if result.status != "NO_AUDIT_REGRESSION":
            rows.append(CandidateComparisonRow(
                identifier, result.status, "EXCLUDED",
                f"Excluded: {result.status}. No improvement recommendation is made.",
            ))
            continue

        # Fail closed if an otherwise passing evaluation lacks its evidence.
        if (
            trial.status != "REAUDITED"
            or after is None
            or after.status == "BLOCKED"
            or result.regression is None
            or result.regression.status != "NO_AUDIT_REGRESSION"
        ):
            rows.append(CandidateComparisonRow(
                identifier, "EVIDENCE_INVALID", "EXCLUDED",
                "A passing audit-regression assessment and completed trial are required.",
            ))
            continue

        if not _improves(after, trial.audit_before):
            rows.append(CandidateComparisonRow(
                identifier, result.status, "NO_MEASURED_IMPROVEMENT",
                "No reduction in finding severity/count or duplicate count was measured.",
            ))
            continue

        improving[identifier] = after
        rows.append(CandidateComparisonRow(
            identifier, result.status, "IMPROVING",
            "Measured audit improvement with no detected audit regression.",
        ))

    shortlist = tuple(sorted(
        identifier for identifier, after in improving.items()
        if not any(
            other != identifier and _dominates(other_after, after)
            for other, other_after in improving.items()
        )
    ))

    equivalent_output_preference = False
    if len(shortlist) > 1:
        # Only collapse equivalent candidates when the independent trials
        # created EXACTLY the same output bytes and matching audit evidence.
        # Identical scores alone are insufficient: two different outputs can
        # legitimately have different business meaning or hidden trade-offs.
        finalists = [
            result.trial
            for result in evaluations
            if result.trial.assessment.candidate.candidate_id in shortlist
        ]
        if len(finalists) == len(shortlist):
            first = finalists[0]
            first_after = first.audit_after
            first_hash = first.output_fingerprint_sha256
            identical_output = (
                first_after is not None
                and first_hash is not None
                and first_after.fingerprint_sha256 == first_hash
                and all(
                    trial.audit_after is not None
                    and trial.output_fingerprint_sha256 == first_hash
                    and trial.audit_after.fingerprint_sha256 == first_hash
                    and trial.audit_after.status == first_after.status
                    and trial.audit_after.quality_score == first_after.quality_score
                    and trial.audit_after.row_count == first_after.row_count
                    and trial.audit_after.column_count == first_after.column_count
                    and trial.audit_after.duplicate_row_count == first_after.duplicate_row_count
                    and trial.audit_after.risk_flags == first_after.risk_flags
                    and _profile(trial.audit_after) == _profile(first_after)
                    for trial in finalists
                )
            )
            if identical_output:
                by_complexity = sorted(
                    (
                        len(trial.assessment.candidate.repair_plan.actions),
                        trial.assessment.candidate.candidate_id,
                    )
                    for trial in finalists
                )
                # Do not arbitrarily choose between equally simple plans.
                if by_complexity[0][0] < by_complexity[1][0]:
                    shortlist = (by_complexity[0][1],)
                    equivalent_output_preference = True

    if len(shortlist) == 1:
        status = "RECOMMENDED"
        recommended = shortlist[0]
        message = (
            "Independent trials produced identical repaired bytes and matching "
            "audits; the strictly simpler approved plan is recommended. "
            "Customer authorization is still required before export."
            if equivalent_output_preference else
            "One improving candidate leads on the measured evidence; "
            "release is not authorized."
        )
    elif shortlist:
        status = "HUMAN_CHOICE_REQUIRED"
        recommended = None
        message = (
            "Tied evidence or trade-offs remain; "
            "no automatic winner or release authorization."
        )
    else:
        status = "NO_IMPROVING_CANDIDATE"
        recommended = None
        message = (
            "No eligible measured improvement; "
            "no candidate is recommended or released."
        )

    return CandidateRecommendation(
        checked.source_fingerprint_sha256,
        status,
        recommended,
        shortlist,
        tuple(rows),
        evaluations,
        message,
    )
